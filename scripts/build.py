def count_sigma_documents() -> tuple[int, int]:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from sigma_eval import load_rule_file  # noqa: PLC0415

    docs = 0
    for path in sorted((ROOT / "rules" / "sigma").glob("TH-*.yml")):
        detections, correlations = load_rule_file(path)
        docs += len(detections) + len(correlations)

    cases = 0
    for path in sorted((ROOT / "tests" / "rules").glob("TH-*.yml")):
        fixture = load_yaml(path.read_text(encoding="utf-8"))
        cases += len(fixture.get("cases", []))
    return docs, cases


def build(check: bool) -> int:
    playbooks = load_playbooks()
    reference = load_reference()
    atomics = load_atomics()
    sigma_docs, test_cases = count_sigma_documents()

    outputs: dict[Path, str] = {}

    readme_path = ROOT / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    readme = replace_block(readme, "coverage-table", render_readme_table(playbooks, reference))
    readme = replace_block(
        readme, "stats", render_readme_stats(playbooks, reference, sigma_docs, test_cases)
    )
    outputs[readme_path] = readme

    mkdocs_path = ROOT / "mkdocs.yml"
    if mkdocs_path.exists():
        mkdocs = mkdocs_path.read_text(encoding="utf-8")
        begin, end = "# BEGIN GENERATED NAV", "# END GENERATED NAV"
        if begin in mkdocs and end in mkdocs:
            head = mkdocs.split(begin)[0]
            tail = mkdocs.split(end)[1]
            mkdocs = f"{head}{begin}\n{render_mkdocs_nav(playbooks)}\n{end}{tail}"
            outputs[mkdocs_path] = mkdocs

    outputs[MAPPINGS / "attack-coverage.md"] = render_coverage_matrix(playbooks, reference, atomics)
    outputs[MAPPINGS / "attack-navigator-layer.json"] = render_navigator_layer(playbooks, reference)
    outputs[MAPPINGS / "legacy-technique-ids.md"] = render_legacy_ids(reference, playbooks)
    outputs[VALIDATION / "atomic-coverage.md"] = render_atomic_coverage(playbooks, atomics)
    outputs[PLAYBOOKS / "README.md"] = render_playbook_index(playbooks, reference)

    stale: list[str] = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == content:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    if check:
        if stale:
            print("Generated files are out of date; run scripts/build.py:", file=sys.stderr)
            for name in stale:
                print(f" - {name}", file=sys.stderr)
            return 1
        print(f"Generated files are current ({len(outputs)} artefacts).")
        return 0

    print(
        f"Regenerated {len(outputs)} artefacts from {len(playbooks)} playbooks "
        f"({sigma_docs} Sigma documents, {test_cases} test cases)."
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if any generated file is stale")
    args = parser.parse_args()
    return build(args.check)


if __name__ == "__main__":
    sys.exit(main())
